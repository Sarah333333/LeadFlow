#!/usr/bin/env bash
# Builds supabase/setup/all_migrations.sql from supabase/migrations/*.sql (in order), for pasting into the
# Supabase SQL Editor of a NEW, EMPTY project. Re-run whenever a migration is added.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=supabase/setup/all_migrations.sql
{
  echo "-- LeadFlow AI — complete database schema (GENERATED by scripts/combine-migrations.sh — do not edit by hand)"
  echo "-- Run ONCE in the Supabase SQL Editor of a NEW, EMPTY project."
  echo "-- Runs in a single transaction: if anything fails, nothing is applied."
  echo "-- It also records each migration in supabase_migrations.schema_migrations, so a later"
  echo "-- \`supabase db push\` will not try to apply them again."
  echo
  echo "begin;"
  for f in supabase/migrations/*.sql; do
    echo
    echo "-- ═════════════════════════════ $(basename "$f") ═════════════════════════════"
    cat "$f"
  done
  echo
  echo "-- ═════════════════════════════ migration history (for the Supabase CLI) ═════════════════════════════"
  echo "create schema if not exists supabase_migrations;"
  echo "create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);"
  for f in supabase/migrations/*.sql; do
    b=$(basename "$f" .sql); v=${b%%_*}; n=${b#*_}
    echo "insert into supabase_migrations.schema_migrations (version, name) values ('$v', '$n') on conflict (version) do nothing;"
  done
  echo
  echo "commit;"
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines, $(ls supabase/migrations/*.sql | wc -l) migrations)"
